function entry(
  level: JlptLevel,
  partOfSpeech: PartOfSpeech,
  surface: string,
  reading: string,
  meaningZh: string
): VocabularyItem {
  return {
    id: `${level.toLowerCase()}-${surface}`,
    surface,
    reading,
    meaningZh,
    partOfSpeech,
    group: null,
    lesson: null,
    tags: [],
    examples: [],
    level
  };
}

